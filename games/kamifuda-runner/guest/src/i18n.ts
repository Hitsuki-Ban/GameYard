const CATALOGS = Object.freeze({ ja, en, "zh-Hans": zhHans }) satisfies Readonly<
  Record<KamifudaLocale, Catalog>
>;

function assertLocale(value: string): asserts value is KamifudaLocale {
  if (!SUPPORTED_LOCALES.includes(value as KamifudaLocale)) {
    throw new RangeError(`Unsupported Host locale: ${value}`);
  }
}

function interpolate(message: string, params: Readonly<Record<string, string | number>>): string {
  return message.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_match, name: string) => {
    if (!Object.prototype.hasOwnProperty.call(params, name)) {
      throw new RangeError(`Missing translation parameter: ${name}`);
    }
    return String(params[name]);
  });
}

export function createKamifudaI18n(initialLocale: string) {
  assertLocale(initialLocale);
  let locale: KamifudaLocale = initialLocale;
  const numberFormats = new Map<KamifudaLocale, Intl.NumberFormat>();

  const api = {
    get locale(): KamifudaLocale {
      return locale;
    },
    setLocale(nextLocale: string): boolean {
      assertLocale(nextLocale);
      if (nextLocale === locale) return false;
      locale = nextLocale;
      return true;
    },
    t(key: MessageKey, params: Readonly<Record<string, string | number>> = {}): string {
      const message = CATALOGS[locale][key];
      if (message === undefined) throw new RangeError(`Unknown translation key: ${key}`);
      return interpolate(message, params);
    },
    number(value: number): string {
      let formatter = numberFormats.get(locale);
      if (!formatter) {
        formatter = new Intl.NumberFormat(locale);
        numberFormats.set(locale, formatter);
      }
      return formatter.format(value);
    },
    applyDocument(document: Document): void {
      document.documentElement.lang = locale;
      document.title = api.t("page.title");
      const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
      if (!description) throw new Error("Kamifuda localization requires meta[name=description].");
      description.content = api.t("page.description");
      for (const element of document.querySelectorAll<HTMLElement>("[data-i18n]")) {
        const key = element.dataset.i18n as MessageKey | undefined;
        if (!key) throw new Error("A data-i18n element requires a translation key.");
        element.textContent = api.t(key);
      }
      for (const element of document.querySelectorAll<HTMLElement>("[data-i18n-aria-label]")) {
        const key = element.dataset.i18nAriaLabel as MessageKey | undefined;
        if (!key) throw new Error("A data-i18n-aria-label element requires a translation key.");
        element.setAttribute("aria-label", api.t(key));
      }
    },
  };
  return api;
}

export type KamifudaI18n = ReturnType<typeof createKamifudaI18n>;
