type MessageKey = keyof typeof ja;
type Catalog = { readonly [Key in MessageKey]: string };

type Placeholders<Message extends string> = Message extends `${string}{${infer Name}}${infer Rest}`
  ? Name | Placeholders<Rest>
  : never;
type SamePlaceholders<Left extends string, Right extends string> =
  Exclude<Placeholders<Left>, Placeholders<Right>> extends never
    ? Exclude<Placeholders<Right>, Placeholders<Left>> extends never
      ? true
      : false
    : false;
type CatalogParity<Candidate extends Catalog> = {
  readonly [Key in MessageKey]: Candidate[Key] extends ""
    ? never
    : SamePlaceholders<(typeof ja)[Key], Candidate[Key]> extends true
      ? Candidate[Key]
      : never;
};

function defineCatalog<const Candidate extends Catalog>(
  catalog: Exclude<keyof Candidate, MessageKey> extends never
    ? Candidate & CatalogParity<Candidate>
    : never,
): Candidate {
  return catalog;
}

