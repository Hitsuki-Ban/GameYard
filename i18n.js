  function deepFreeze(value) {
    Object.freeze(value);
    Object.values(value).forEach(item => {
      if (item && typeof item === 'object' && !Object.isFrozen(item)) deepFreeze(item);
    });
    return value;
  }

  function placeholders(message) {
    return [...message.matchAll(/\{([A-Za-z][A-Za-z0-9]*)\}/g)].map(match => match[1]).sort();
  }

  const referenceKeys = Object.keys(catalogs.en).sort();
  for (const locale of LOCALES) {
    const keys = Object.keys(catalogs[locale]).sort();
    if (keys.length !== referenceKeys.length || keys.some((key, index) => key !== referenceKeys[index])) {
      throw new Error(`CrownBreakerI18n catalog keys differ for ${locale}.`);
    }
    for (const key of referenceKeys) {
      if (typeof catalogs[locale][key] !== 'string') throw new Error(`CrownBreakerI18n value must be a string: ${locale}.${key}`);
      const expected = placeholders(catalogs.en[key]);
      const actual = placeholders(catalogs[locale][key]);
      if (expected.length !== actual.length || expected.some((name, index) => name !== actual[index])) {
        throw new Error(`CrownBreakerI18n placeholders differ: ${locale}.${key}`);
      }
    }
  }

  function assertPreference(preference) {
    if (!PREFERENCES.includes(preference)) throw new RangeError(`Unsupported language preference: ${String(preference)}`);
    return preference;
  }

  function matchLanguageTag(tag) {
    if (typeof tag !== 'string' || !tag.trim()) return null;
    const normalized = tag.trim().toLowerCase();
    if (normalized === 'zh' || normalized.startsWith('zh-')) return 'zh-CN';
    if (normalized === 'ja' || normalized.startsWith('ja-')) return 'ja';
    if (normalized === 'en' || normalized.startsWith('en-')) return 'en';
    return null;
  }

  function systemLocale() {
    const nav = globalThis.navigator;
    if (!nav) return 'en';
    const tags = Array.isArray(nav.languages) ? [...nav.languages, nav.language] : [nav.language];
    for (const tag of tags) {
      const match = matchLanguageTag(tag);
      if (match) return match;
    }
    return 'en';
  }

  function resolveLocale(preference) {
    assertPreference(preference);
    return preference === 'system' ? systemLocale() : preference;
  }

  function translate(locale, key, params) {
    if (!LOCALES.includes(locale)) throw new RangeError(`Unsupported locale: ${String(locale)}`);
    if (!Object.prototype.hasOwnProperty.call(catalogs[locale], key)) throw new ReferenceError(`Missing translation key: ${locale}.${String(key)}`);
    const message = catalogs[locale][key];
    const required = placeholders(message);
    if (required.length && (!params || typeof params !== 'object')) throw new TypeError(`Missing interpolation parameters: ${locale}.${key}`);
    for (const name of required) {
      if (!Object.prototype.hasOwnProperty.call(params, name)) throw new TypeError(`Missing interpolation parameter "${name}": ${locale}.${key}`);
    }
    return message.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_, name) => String(params[name]));
  }

  globalThis.CrownBreakerI18n = Object.freeze({
    preferences: Object.freeze([...PREFERENCES]),
    locales: Object.freeze([...LOCALES]),
    catalogs: deepFreeze(catalogs),
    assertPreference,
    resolveLocale,
    translate
  });
